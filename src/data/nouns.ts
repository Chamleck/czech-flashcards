// Набір підібраний так, щоб покрити всі 11 базових зразків (взорів) чеської мови,
// з опорою на частотні, повсякденні слова.
//
// УВАГА: варіантні форми (напр. dativ pánovi/pánu) подано через "/". Це нормативні
// дублети сучасної чеської. Рекомендована звірка з носієм перед фінальним релізом.
//
// ПРАВИЛА ДОДАВАННЯ ІМЕННИКІВ
//  1. Усі 14 клітинок (7 відмінків × 2 числа) заповнені; «—» лише для pluralia / singularia tantum
//     (вся форма одного числа): peníze, brýle, kalhoty, ústa — без однини. Рушії квізу самі обирають число.
//     Дублети через « / »: перша форма — та, яку показуємо як правильну.
//  2. category — з data/categories.ts. Дні й місяці/пори року (unsuitableAsPartner) у «чужі» речення
//     не підставляються.
//  3. sem — ОБОВ'ЯЗКОВЕ поле: смислові теги з data/nounTags.ts (кожен тег має пояснення й приклади в
//     NOUN_TAG_DOC). Без sem проєкт не збереться. За тегами квіз «Прийменники» САМ вирішує, у які фрази
//     слово підходить («Jsem v ___» — placeV, «Polož to na ___» — surface, «Čekám na ___» — person…):
//     список фраз не редагуємо. Правила:
//       • став лише ті теги, про які можеш сказати «так» без вагань; зайвий тег = неприродна фраза в квізі,
//         бракуючий тег = слово просто рідше з'являється (безпечно);
//       • місце ЗАВЖДИ має рівно один із placeV (в школі) чи placeNa (на пошті) — це лексична властивість
//         слова; перевір за словником, а не за відчуттям;
//       • особа, тварина, їжа, час, погода, гроші, документ, тіло, повітря — «самотні» теги (без інших; винятки:
//         тіло + bodyLevel / singleLevel / bodyMany, час + timeUnit / dayPart, їжа + served / homemade, документ + carried — pas, doklad);
//       • їжа: served — страва чи напій, який подають теплим або холодним (káva, polévka, maso: «teplá polévka»);
//         homemade — буває домашнім (chléb, pivo, ovoce: «domácí chléb»); жодного — як cukr. Без них teplý / studený /
//         domácí з цим словом не з'являться (і «studený cukr» теж) — це безпечно; зайвий тег дасть безглузду пару;
//       • повітря (vzduch) — air, НЕ weather: weather бере квіз «Прийменники» у «při ___» («při vzduchu» — ні);
//       • новий смисловий клас, для якого жоден тег не відділяє погані пари від добрих (як було з cukr і vzduch), —
//         новий тег із поясненням у NOUN_TAG_DOC (data/nounTags.ts), а не виняток для слова: списків слів у коді немає;
//       • dev-збірка пише в консоль, якщо набір тегів суперечливий (validateNounSem).
//  4. variants (необов'язково) — прийнятні, але НЕ показані на картці форми клітинки, що збігаються з формою
//     ІНШОГО відмінка цього слова (родовий kostel: kostela, але вживають і kostelu = давальний). Квіз не подасть
//     таку форму як помилкову відповідь. Знайти такі випадки можна звіркою зі словником форм (MorfFlex).
//  5. Початкова група приголосних слова, якої ще немає в CLUSTER_RULES (data/prepositionPartners.ts), не дає
//     взяти слово у фрази з v/k/s/z (ve/ke/se/ze неочевидні): додай рядок у CLUSTER_RULES за правилом IJP
//     («Vokalizace předložek»). Де IJP фіксує коливання (обидві форми вживані), прийменник у рядку НЕ пишемо —
//     квіз таку фразу свідомо не ставить.
//  6. Нове слово само потрапляє в усі фрази квізу, чиї теги збігаються (FIXED_FRAMES, DUAL_FRAMES). Після
//     додавання прочитай фрази, куди воно потрапило (кожен фрейм + це слово): тег, що дає безглузду фразу, прибери.
//  7. plGender — якщо в множині прикметники узгоджуються з іншим родом, ніж в однині (děti, oči, uši — як жіночий:
//     «malé děti», «modré oči»). Без цього квіз «Прикметники та займенники» склав би «ta malá děti».
//  8. Квіз «Прикметники та займенники» теж бере іменник за тегами: у фрази (data/declensionFrames.ts) і в пари з
//     прикметниками (поле fits у data/adjectives.ts). Після додавання прочитай і ці фрази та пари.
//  9. Квіз «Числівники» теж бере іменник за тегами (data/numeralFrames.ts). uncountable — ОБОВ'ЯЗКОВЕ рішення (без
//     нього проєкт не збереться): true — слово не рахують штуками (voda, rýže, peníze), у цей квіз воно не потрапляє,
//     а в множинних фразах інших квізів не стоїть; false — звичайний злічуваний іменник. Слово лише з множиною (вся однина «—») квіз сам
//     рахує через jedny / dvoje / troje / čtvery (поле pluralOnly у data/cardinals.ts) і через pět+: окремо нічого
//     не позначай. Після додавання прочитай фрази цього квізу, куди слово потрапило.
// 10. Квіз «Іменники» питає саме слово в реченнях з data/nounFrames.ts, теж за тегами. Не питає називний однини
//     (заголовок картки; у слів лише з множиною — називний множини) і кличний слів без тегу person / animal.
//     Якщо під теги слова в якомусь відмінку й числі не підійшла жодна фраза, квіз питає форму без речення —
//     dev-збірка друкує такі комбінації; прочитай фрази, куди слово потрапило, і за потреби додай фразу
//     (правила — у шапці data/nounFrames.ts).
// 11. Форми — за двома джерелами (IJP + en.wiktionary / MorfFlex); дублет, де обидві форми правильні, НЕ подаємо через
//     « / » — лише першу форму IJP (cukre, vzduchách), решта прийнятна й так.
// 12. Місяць (leden … prosinec) — поле month: номер, найбільший день (лютий — 29) і ukGen — українська назва в родовому
